/**
 * Seconds that give exactly `frames` frames at the original 30000/1001 fps
 * (`round(sec * fps)` returns `frames`). Keeps the defaults frame-exact.
 */
function ntscFrames(frames: number): number {
  return (frames * 1001) / 30000;
}

